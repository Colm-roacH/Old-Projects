    /**
     * Updates the equation whenever a new value is added
     * @param value The value being added, "1", "7", "9", " + ", " ÷ ", etc.
     */
    private void updateEquation(String value) {
        equation = equation + value;
        output.setText(equation);
    }
    
    /**
     * Counts the opening and closing parentheses to see if they are equal
     * @return If they aren't, return false, if they are, return true
     */
    public boolean equalParentheses() {
        int openCount = 0;
        int closeCount = 0;
        for(int i = 0; i<equation.length(); i++){
            if(equation.charAt(i) == '('){openCount++;}
            if(equation.charAt(i) == ')'){closeCount++;}
        }
        if(openCount == closeCount){
            return true;
        }
        return false;
    }
    
