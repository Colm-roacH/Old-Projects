    private static boolean isNumeric(String s) {  
        return s != null && s.matches("[-+]?\\d*\\.?\\d+");  
    }
    
    private static double calc(double x, String op, double y) {
        if(op.equals("+")) return x + y;
        if(op.equals("-")) return x - y;
        if(op.equals("×")) return x * y;
        if(op.equals("÷")){
            if(y == 0){dividedByZero = true;}
            return x / y;
        }
        return 0;
    }
    
    public static int opOrder(String op) {
        return precedence[operators.indexOf(op)];
    }
    
    private static boolean validateBrackets(String[] tokens) {
        int balance = 0;
        for (String token : tokens) {
            if (token.equals("(")) balance++;
            else if (token.equals(")")) balance--;
            if (balance < 0) return false;
        }
        return balance == 0;
    }
    
    public static double calc(String s) {
        Stack<Double> values = new Stack<Double>();
        Stack<String> ops = new Stack<String>();
        String[] eqn = s.split(" ");
        for(String token:eqn) {
            if (isNumeric(token)) values.push(Double.parseDouble(token));
            else if(token.equals("(")) ops.push(token);
            else if(token.equals(")")) {
                while(!ops.peek().equals("(")) {
                    String op = ops.pop();
                    Double y = values.pop();
                    Double x = values.pop();
                    values.push(calc(x, op, y));
                }
                ops.pop();
            }
            else if(operators.contains(token)) {
                while(!ops.empty() && opOrder(ops.peek()) >= opOrder(token)) {
                    String op = ops.pop();
                    Double y = values.pop();
                    Double x = values.pop();
                    values.push(calc(x, op, y));
                }
                ops.push(token);
            }
            
            /*
            * Uncomment these two lines to see a printout of the value 
            * and operator stack at each stage of the calculation
            */
            
            //System.out.println("Values: " + values);
            //System.out.println("Operators: " + ops);
        }
        while(!ops.empty()) {
            String op = ops.pop();
            Double y = values.pop();
            Double x = values.pop();
            values.push(calc(x, op, y));			
        }
        return values.pop();	
    }
    
