    private void equalsButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_equalsButtonActionPerformed
        //Checks to see if the first character is a space, which should only happen when an operator comes first, causing an error
        if(equation.charAt(0) == ' '){equation = "ERR";}
        //Calls a method to calculate if the paranthesis are equal, if they aren't display an error
        else if(!equalParentheses()){equation = "ERR";}
        //Actually calculates and updates the equation
        else{equation = ""+calc(equation);}
        //Displays an error instead of "Infinity" if anything is ever divided by zero
        if(dividedByZero){equation = "ERR";}
        //Updates display
        output.setText(equation);
        //Updates static variables
        replace = true; 
        dividedByZero = false;
    }//GEN-LAST:event_equalsButtonActionPerformed

